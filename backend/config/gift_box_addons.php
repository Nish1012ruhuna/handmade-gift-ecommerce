function getGiftBoxAddonsByIds($addonIds)
{
    if (!is_array($addonIds)) {
        throw new InvalidArgumentException("Invalid gift-box item selection.");
    }

    $catalog = [];
    foreach (giftBoxAddonCatalog() as $addon) {
        $catalog[$addon["id"]] = $addon;
    }

    $selected = [];
    foreach ($addonIds as $rawId) {
        $id = filter_var($rawId, FILTER_VALIDATE_INT);

        if ($id === false || !isset($catalog[$id]) || isset($selected[$id])) {
            throw new InvalidArgumentException("One or more selected gift-box items are invalid.");
        }

        $selected[$id] = $catalog[$id];
    }

    return array_values($selected);
}

function saveGiftBoxAddons($conn, $addons)
{
    if (count($addons) === 0) {
        return null;
    }

    $selection = [];
    foreach ($addons as $addon) {
        $selection[] = [
            "id" => $addon["id"],
            "name" => $addon["name"],
            "price" => $addon["price"]
        ];
    }

    $instructions = json_encode($selection, JSON_UNESCAPED_SLASHES);
    if ($instructions === false) {
        throw new RuntimeException("Unable to save selected gift-box items.");
    }

    $name = "Gift box item selection";
    $stmt = $conn->prepare(
        "INSERT INTO customization (CustomName, SpecialInstruction) VALUES (?, ?)"
    );

    if (!$stmt) {
        throw new RuntimeException("Unable to prepare gift-box customization.");
    }

    $stmt->bind_param("ss", $name, $instructions);
    if (!$stmt->execute()) {
        $stmt->close();
        throw new RuntimeException("Unable to save gift-box customization.");
    }

    $customizationId = (int) $conn->insert_id;
    $stmt->close();

    return $customizationId;
}
